/**
 * Records the `--help` output of every command of a `surreal` binary in
 * `src/data/cli-help.txt`, for a reviewer to read the change that a release makes
 * to the command line. No page shows it and nothing in `public/` serves it. The
 * option tables of the command pages are what readers see, and
 * `check-cli-reference.ts` compares those with `public/cli-history/data.json`.
 *
 *   bun scripts/cli-help/generate.ts <surreal binary>
 *   bun scripts/cli-help/generate.ts --check <surreal binary>
 *
 * The commands are found by following the `Commands:` list of each help text from
 * `surreal` downwards, so a hidden command is not recorded. Help is written at a
 * fixed width, so that the file does not change with the size of a terminal. With
 * `--check` nothing is written, and the exit code says whether the file is
 * the output of this binary.
 */
import { join } from "node:path";

const OUT = join(import.meta.dir, "../../src/data/cli-help.txt");
const args = process.argv.slice(2);
const check = args.includes("--check");
const binary = args.find((arg) => !arg.startsWith("--"));

if (!binary) {
    console.error("usage: bun scripts/cli-help/generate.ts [--check] <surreal binary>");
    process.exit(1);
}

function help(command: string[]): string {
    const run = Bun.spawnSync([binary as string, ...command, "--help"], {
        env: { ...process.env, COLUMNS: "100", NO_COLOR: "1" },
    });

    return run.stdout.toString().trimEnd();
}

/** The subcommands that a help text lists, other than `help` itself. */
function subcommands(text: string): string[] {
    const section = /^Commands:\n((?: {2}\S.*\n?|\s*\n)+)/m.exec(`${text}\n`)?.[1] ?? "";

    return section
        .split("\n")
        .map((line) => /^ {2}(\S+)/.exec(line)?.[1])
        .filter((name): name is string => Boolean(name) && name !== "help");
}

const version = /(\d+\.\d+\.\d+(?:-[\w.]+)?)/.exec(
    Bun.spawnSync([binary, "--version"]).stdout.toString(),
)?.[1];
const sections: string[] = [];

function walk(command: string[]) {
    const text = help(command);

    sections.push(`## ${["surreal", ...command].join(" ")}\n\n${text}\n`);

    for (const name of subcommands(text)) walk([...command, name]);
}

walk([]);

const output = `# Command help of SurrealDB ${version}\n\nGenerated by scripts/cli-help/generate.ts. This is a record for review and is not published.\n\n${sections.join("\n")}`;

if (check) {
    const stored = (await Bun.file(OUT).exists()) ? await Bun.file(OUT).text() : "";

    if (stored !== output) {
        console.error(`[cli-help] src/data/cli-help.txt is not the output of ${version}`);
        process.exit(1);
    }

    console.log(`[cli-help] src/data/cli-help.txt matches ${version}`);
} else {
    await Bun.write(OUT, output);
    console.log(
        `[cli-help] ${sections.length} commands of ${version} written to src/data/cli-help.txt`,
    );
}
